"""Head-detector dataset for method D, with a clean three-way split.

PAMELA-UANDES ships R1–R4 as "train" and R5–R8 as "test". Method D needs a
third bucket: its tracker and counting rule have knobs, and tuning those on the
test clips would make the final numbers meaningless. So:

    R1–R3  -> detector training images
    R4     -> detector validation + tracker/counter tuning (never trained on)
    R5–R8  -> final test, touched once

Frames are kept at the native 352x288 — upscaling to 640 (as import_pamela does
for method A) adds pixels, not information, and a head is already ~32 px.

    python -m backend.training.build_head_dataset
"""
from __future__ import annotations

import argparse
import os
import shutil

import cv2

from backend.training.import_pamela import ROOT, TRAIN_CLIPS, _load_csv

DEV_SUFFIX = "_R4"


def build(out_dir: str, every_train: int, every_val: int) -> None:
    root = os.path.abspath(out_dir)
    if os.path.exists(root):
        shutil.rmtree(root)
    for split in ("train", "val"):
        os.makedirs(f"{root}/images/{split}", exist_ok=True)
        os.makedirs(f"{root}/labels/{split}", exist_ok=True)

    stats = {"train": 0, "val": 0, "boxes": 0}
    for tag, csv_rel in TRAIN_CLIPS.items():
        split = "val" if tag.endswith(DEV_SUFFIX) else "train"
        every = every_val if split == "val" else every_train
        by_frame = _load_csv(f"{ROOT}/{csv_rel}")
        cap = cv2.VideoCapture(f"{ROOT}/{tag}.mpg")
        for fi in sorted(by_frame)[::every]:
            cap.set(cv2.CAP_PROP_POS_FRAMES, fi)
            ok, frame = cap.read()
            if not ok:
                continue
            h, w = frame.shape[:2]
            rows = []
            for _pid, x, y, bw, bh in by_frame[fi]:
                # Clip to the frame: a head half out of view is still a head
                x1, y1 = max(0.0, x), max(0.0, y)
                x2, y2 = min(float(w), x + bw), min(float(h), y + bh)
                if x2 - x1 < 2 or y2 - y1 < 2:
                    continue
                rows.append(f"0 {(x1 + x2) / 2 / w:.6f} {(y1 + y2) / 2 / h:.6f} "
                            f"{(x2 - x1) / w:.6f} {(y2 - y1) / h:.6f}")
            name = f"{tag}_{fi:06d}"
            cv2.imwrite(f"{root}/images/{split}/{name}.jpg", frame,
                        [cv2.IMWRITE_JPEG_QUALITY, 95])
            with open(f"{root}/labels/{split}/{name}.txt", "w") as fh:
                fh.write("\n".join(rows) + ("\n" if rows else ""))
            stats[split] += 1
            stats["boxes"] += len(rows)
        cap.release()
        print(f"  {tag:16} -> {split}")

    with open(f"{root}/data.yaml", "w") as fh:
        fh.write(f"# Auto-generated by backend/training/build_head_dataset.py\n"
                 f"path: {root}\ntrain: images/train\nval: images/val\n\n"
                 f"names:\n  0: head\n")
    print(f"\ntrain={stats['train']} val={stats['val']} boxes={stats['boxes']}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="datasets/pamela_head")
    ap.add_argument("--every-train", type=int, default=2)
    ap.add_argument("--every-val", type=int, default=5)
    args = ap.parse_args()
    build(args.out, args.every_train, args.every_val)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
