"""Build a top-view pose dataset by distilling a large teacher onto our own footage.

Public top-view datasets (PIROPO, AVSS 2007) carry boxes or counts, never the 17
COCO keypoints that method B's shoulder anchor needs — so they cannot fine-tune a
pose model directly. What *is* available is the knowledge already inside a large
pose model: yolo11m-pose at 1280px finds ~5.7 people per top-view frame with 4.3
usable shoulder pairs, against 2.2/1.7 for the nano model the method actually
runs. This script harvests the teacher's answers as labels so the nano student can
learn them.

The teacher reads the full-resolution frame at high imgsz; the student's copy of
the image is saved at deployment width. Labels are normalised, so they carry over.

    python -m backend.training.build_dataset --teacher yolo11m-pose.pt
"""
from __future__ import annotations

import argparse
import os
import shutil
from dataclasses import dataclass

import cv2
import numpy as np

# Segments containing genuine doorway footage. The rest of these files is vendor
# marketing; see the counting-methods findings for how these were located.
@dataclass
class Segment:
    path:  str
    start: float
    end:   float
    tag:   str


# Every segment must be a camera looking DOWN at a doorway. Street-level and
# side-on shots were deliberately removed: this fine-tune exists to undo COCO's
# upright-pedestrian bias, and feeding it upright pedestrians defeats the point.
#
# STONKAM 19.0-25.0s is deliberately absent: that stretch is the end-to-end
# counting benchmark, and training on it would make the evaluation meaningless.
SEGMENTS = [
    Segment("test_data/quality/Bus Passenger Counting Camera.mp4", 25.0,  40.0, "stonkam"),
    Segment("test_data/quality/How does passenger counter work？How does the passenger counting system work？  HPC168.mp4",
            94.0, 118.0, "hpc168"),
    Segment("test_data/quality/Hikvision Passenger Counting Camera.mp4", 52.0, 61.0, "hikvis_a"),
    Segment("test_data/quality/Hikvision Passenger Counting Camera.mp4", 68.0, 92.0, "hikvis_b"),
]

KPT_SHAPE = (17, 3)
# COCO left/right keypoint swap, applied when the trainer mirrors an image
FLIP_IDX = [0, 2, 1, 4, 3, 6, 5, 8, 7, 10, 9, 12, 11, 14, 13, 16, 15]

DATA_YAML = """# Auto-generated by backend/training/build_dataset.py
path: {root}
train: images/train
val: images/val

kpt_shape: [17, 3]
flip_idx: {flip}

names:
  0: person
"""


def teacher_label(model, frame, imgsz: int, conf: float, device: str, tta: bool,
                  min_kpts: int = 2):
    """Run the teacher and return YOLO-pose label rows (normalised)."""
    res = model.predict(frame, conf=conf, imgsz=imgsz, device=device,
                        augment=tta, verbose=False)[0]
    if res.boxes is None or not len(res.boxes):
        return []

    h, w = frame.shape[:2]
    xyxy = res.boxes.xyxy.cpu().numpy()
    kxy  = res.keypoints.xy.cpu().numpy() if res.keypoints is not None else None
    kcf  = (res.keypoints.conf.cpu().numpy()
            if res.keypoints is not None and res.keypoints.conf is not None else None)

    rows = []
    for i, (x1, y1, x2, y2) in enumerate(xyxy):
        bw, bh = (x2 - x1) / w, (y2 - y1) / h
        # Drop specks: they are usually background texture, not a boarding passenger
        if bw <= 0 or bh <= 0 or bw * bh < 0.0015:
            continue
        cx, cy = (x1 + x2) / 2 / w, (y1 + y2) / 2 / h
        vals = [0, cx, cy, bw, bh]

        for j in range(KPT_SHAPE[0]):
            if kxy is None or i >= len(kxy):
                vals += [0.0, 0.0, 0]
                continue
            px, py = kxy[i][j][0] / w, kxy[i][j][1] / h
            c = float(kcf[i][j]) if kcf is not None else 1.0
            # 2 = labelled+visible, 0 = not labelled. Anything off-frame is dropped
            # so the student is never taught a keypoint the teacher hallucinated.
            v = 2 if (c > 0.3 and 0.0 <= px <= 1.0 and 0.0 <= py <= 1.0) else 0
            vals += [round(px, 6) if v else 0.0, round(py, 6) if v else 0.0, v]

        # A real person seen from above still shows a head and some shoulders.
        # A box with no keypoint support is almost always the teacher latching
        # onto a logo or a seat, so it is dropped rather than taught.
        if sum(1 for j in range(KPT_SHAPE[0]) if vals[5 + j * 3 + 2] == 2) < min_kpts:
            continue
        rows.append(vals)
    return rows


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--teacher", default="yolo11m-pose.pt")
    ap.add_argument("--out", default="datasets/topview_pose")
    ap.add_argument("--every", type=int, default=3, help="sample every Nth frame")
    ap.add_argument("--imgsz", type=int, default=1280, help="teacher inference size")
    ap.add_argument("--conf", type=float, default=0.15)
    ap.add_argument("--width", type=int, default=640, help="saved image width (student)")
    ap.add_argument("--val-frac", type=float, default=0.2)
    ap.add_argument("--bg-frac", type=float, default=0.08,
                    help="share of empty frames to keep as negatives")
    ap.add_argument("--no-tta", action="store_true")
    ap.add_argument("--min-kpts", type=int, default=2,
                    help="drop teacher boxes with fewer visible keypoints")
    args = ap.parse_args()

    import torch
    from ultralytics import YOLO
    device = "mps" if torch.backends.mps.is_available() else \
             "cuda" if torch.cuda.is_available() else "cpu"
    print(f"teacher={args.teacher} device={device} tta={not args.no_tta}")
    model = YOLO(args.teacher)

    root = os.path.abspath(args.out)
    if os.path.exists(root):
        shutil.rmtree(root)
    for split in ("train", "val"):
        os.makedirs(f"{root}/images/{split}", exist_ok=True)
        os.makedirs(f"{root}/labels/{split}", exist_ok=True)

    stats = {"train": 0, "val": 0, "boxes": 0, "bg": 0, "skipped": 0}

    for seg in SEGMENTS:
        if not os.path.exists(seg.path):
            print(f"  !! missing {seg.path}")
            continue
        cap = cv2.VideoCapture(seg.path)
        fps = cap.get(cv2.CAP_PROP_FPS) or 25.0
        f0, f1 = int(seg.start * fps), int(seg.end * fps)
        idxs = list(range(f0, f1, args.every))
        # Split along time, not at random: neighbouring frames are near-identical,
        # so a random split would leak the validation set into training.
        cut = int(len(idxs) * (1 - args.val_frac))
        kept = 0

        for n, fi in enumerate(idxs):
            cap.set(cv2.CAP_PROP_POS_FRAMES, fi)
            ok, frame = cap.read()
            if not ok:
                continue
            rows = teacher_label(model, frame, args.imgsz, args.conf,
                                 device, not args.no_tta, args.min_kpts)
            split = "train" if n < cut else "val"

            if not rows:
                # A few people-free frames teach the model what "nobody" looks like
                if (n % 100) / 100.0 >= args.bg_frac:
                    stats["skipped"] += 1
                    continue
                stats["bg"] += 1

            scale = args.width / frame.shape[1]
            small = cv2.resize(frame, (args.width, int(frame.shape[0] * scale)))
            name = f"{seg.tag}_{fi:06d}"
            cv2.imwrite(f"{root}/images/{split}/{name}.jpg", small,
                        [cv2.IMWRITE_JPEG_QUALITY, 92])
            with open(f"{root}/labels/{split}/{name}.txt", "w") as fh:
                for r in rows:
                    fh.write(" ".join(str(v) for v in r) + "\n")

            stats[split] += 1
            stats["boxes"] += len(rows)
            kept += 1
        cap.release()
        print(f"  {seg.tag:12} {len(idxs):4} sampled -> {kept:4} kept")

    with open(f"{root}/data.yaml", "w") as fh:
        fh.write(DATA_YAML.format(root=root, flip=FLIP_IDX))

    print(f"\ntrain={stats['train']} val={stats['val']} "
          f"boxes={stats['boxes']} background={stats['bg']} skipped={stats['skipped']}")
    print(f"data.yaml -> {root}/data.yaml")
    if stats["train"] < 40:
        print("!! very small training set — widen SEGMENTS or lower --every")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
