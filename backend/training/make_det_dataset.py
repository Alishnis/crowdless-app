"""Derive a detection dataset from the distilled pose dataset.

A YOLO-pose label row is `cls cx cy w h  <17×(x y v)>` — its first five fields
are exactly a YOLO detection row. So method A's training set is method B's with
the keypoints dropped: no second pass of the teacher, and both methods end up
trained and validated on identical frames with the identical split, which is what
makes their scores comparable.

Images are symlinked rather than copied; the pose dataset stays the source of
truth for pixels.

    python -m backend.training.make_det_dataset
"""
from __future__ import annotations

import argparse
import os
import shutil

DATA_YAML = """# Auto-generated by backend/training/make_det_dataset.py
path: {root}
train: images/train
val: images/val

names:
  0: person
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="datasets/topview_pose")
    ap.add_argument("--out", default="datasets/topview_det")
    ap.add_argument("--copy", action="store_true", help="copy images instead of symlinking")
    args = ap.parse_args()

    src = os.path.abspath(args.src)
    root = os.path.abspath(args.out)
    if not os.path.isdir(src):
        print(f"!! {src} not found — run backend.training.build_dataset first")
        return 1
    if os.path.exists(root):
        shutil.rmtree(root)

    totals = {}
    for split in ("train", "val"):
        img_dir = f"{root}/images/{split}"
        lbl_dir = f"{root}/labels/{split}"
        os.makedirs(img_dir, exist_ok=True)
        os.makedirs(lbl_dir, exist_ok=True)

        src_lbls = f"{src}/labels/{split}"
        if not os.path.isdir(src_lbls):
            continue

        n_img = n_box = 0
        for name in sorted(os.listdir(src_lbls)):
            if not name.endswith(".txt"):
                continue
            stem = name[:-4]
            src_img = f"{src}/images/{split}/{stem}.jpg"
            if not os.path.exists(src_img):
                continue

            rows = []
            with open(f"{src_lbls}/{name}") as fh:
                for line in fh:
                    parts = line.split()
                    if len(parts) >= 5:
                        rows.append(" ".join(parts[:5]))

            with open(f"{lbl_dir}/{stem}.txt", "w") as fh:
                fh.write("\n".join(rows) + ("\n" if rows else ""))

            dst_img = f"{img_dir}/{stem}.jpg"
            if args.copy:
                shutil.copy(src_img, dst_img)
            else:
                os.symlink(src_img, dst_img)

            n_img += 1
            n_box += len(rows)
        totals[split] = (n_img, n_box)

    with open(f"{root}/data.yaml", "w") as fh:
        fh.write(DATA_YAML.format(root=root))

    for split, (n_img, n_box) in totals.items():
        print(f"  {split:5} {n_img:4} images  {n_box:5} boxes")
    print(f"data.yaml -> {root}/data.yaml")
    return 0 if totals.get("train", (0,))[0] else 1


if __name__ == "__main__":
    raise SystemExit(main())
